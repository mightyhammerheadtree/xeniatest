function guestWasmJs(segments, wasm, hleCalls) {
  const segs = segments.map((s) => `  { addr: ${hex(s.addr)}, data: "${bytesToBase64(s.data)}" }`).join(',\n');
  const calls = [...hleCalls.values()].map((c) => `  { addr: ${hex(c.addr)}, moduleId: "${c.moduleId}", ordinal: ${c.ordinal}, name: "${String(c.name).replace(/"/g, '\\"')}" }`).join(',\n');
  return `/* Generated by Xenon Recompiler. Do not edit. */
window.GUEST_WASM_B64 = "${bytesToBase64(wasm)}";
window.GUEST_SEGMENTS = [
${segs}
];
window.HLE_CALLS = [
${calls}
];
`;
}

const RUNTIME_JS = `/* Generated host for the recompiled guest. Classic script — works from file://. */
(function () {
  'use strict';
  var out = document.getElementById('out');
  var statsEl = document.getElementById('stats');
  var t0 = 0;
  var buf = '';
  function write(s) {
    buf += s;
    if (buf.length > 256 * 1024) buf = buf.slice(-256 * 1024);
    out.textContent = buf;
    out.scrollTop = out.scrollHeight;
  }
  function b64ToBytes(b64) {
    var s = atob(b64);
    var bytes = new Uint8Array(s.length);
    for (var i = 0; i < s.length; i++) bytes[i] = s.charCodeAt(i);
    return bytes;
  }
  function RecompExit(code) { this.code = code; this.name = 'RecompExit'; }
  var imports = {
    xenorecomp: {
      putc: function (ch) { write(String.fromCharCode(ch)); },
      exit: function (code) { throw new RecompExit(code); },
      unimpl: function (addr, word) {
        throw new Error('unimplemented instruction 0x' + (word >>> 0).toString(16) + ' at 0x' + (Number(addr) & 0x03ffffff).toString(16) + ' — see docs/HLE.md');
      },
      icall: function (addr) {
        var target = Number(addr) & 0x03ffffff;
        var hle = hleCalls[target];
        if (hle) {
          var result = hleHost.call(hle.moduleId, hle.ordinal);
          if (imports.__exports && imports.__exports.r3) imports.__exports.r3.value = result;
          return result;
        }
        var fn = imports.__exports && imports.__exports['fn_' + target.toString(16)];
        if (!fn) throw new Error('unimplemented indirect call target 0x' + target.toString(16) + ' (not an HLE import)');
        fn();
        return imports.__exports && imports.__exports.r3 ? imports.__exports.r3.value : 0n;
      },
      mmio_store: function (addr, value, size) {
        var a = Number(addr), n = size | 0, v = BigInt(value);
        var DOOR = 0x00f00ffc;
        for (var i = 0; i < n; i++) {
          var b = Number((v >> BigInt((n - 1 - i) * 8)) & 0xffn);
          if (a + i < DOOR) write(String.fromCharCode(b));
        }
        if (a <= DOOR && DOOR < a + n) throw new RecompExit(0);
      },
      mmio_load: function () { return 0n; },
      sc: function (addr) { throw new Error('system call (sc) reached — the HLE runtime does not model raw sc yet; unimplemented kernel imports trap by name, see docs/HLE.md'); }
    }
  };
  // HLE import map baked in at export time: target addr -> { moduleId, ordinal, name }.
  var hleCalls = {};
  (window.HLE_CALLS || []).forEach(function (c) { hleCalls[c.addr] = c; });
  var hleHost = window.XenonHLE
    ? window.XenonHLE.createHleHost({ onConsoleByte: function (b) { write(String.fromCharCode(b)); } })
    : null;

  var wasmBytes;
  try {
    wasmBytes = b64ToBytes(window.GUEST_WASM_B64);
  } catch (e) {
    out.textContent = 'failed to decode embedded wasm: ' + e.message;
    return;
  }
  WebAssembly.instantiate(wasmBytes, imports).then(function (result) {
    var exports = result.instance.exports;
    imports.__exports = exports;
    if (hleHost) hleHost.attachMemory(exports.memory);
    else if (window.HLE_CALLS && window.HLE_CALLS.length) write('\n[trap] hle.js missing — cannot serve kernel imports\n');
    var mem = new Uint8Array(exports.memory.buffer);
    for (var s = 0; s < window.GUEST_SEGMENTS.length; s++) {
      var seg = window.GUEST_SEGMENTS[s];
      mem.set(b64ToBytes(seg.data), seg.addr & 0x03ffffff);
    }
    var entryKey = Object.keys(exports).find(function (k) { return k.indexOf('fn_') === 0; });
    var entryName = entryKey;
    out.textContent = '';
    t0 = performance.now();
    var code = 0;
    try {
      exports[entryName]();
    } catch (e) {
      if (e instanceof RecompExit || e.name === 'RecompExit') code = e.code | 0;
      else { write('\\n[trap] ' + (e && e.message ? e.message : String(e)) + '\\n'); statsEl.textContent = 'halted with a trap'; return; }
    }
    var ms = (performance.now() - t0).toFixed(1);
    statsEl.textContent = 'guest halted (exit ' + code + ') in ' + ms + ' ms';
  }).catch(function (e) {
    out.textContent = 'instantiate failed: ' + (e && e.message ? e.message : String(e));
  });
})();
`;

