/**
 * Build the file list for the project zip.
 * @param {object} opts
 * @param {string} opts.name    project name (used for zip file name and title)
 * @param {string} opts.kind    'bin' | 'elf' | 'xex'
 * @param {number} opts.entry   guest entry address
 * @param {Uint8Array} opts.wasm   compiled wasm bytes
 * @param {Array<{addr:number, data:Uint8Array}>} opts.segments  image segments
 * @param {{fragments:number, insns:number, blocks:number, unimpl:number}} opts.stats
 * @param {Date} [opts.now]
 * @returns {Array<{name:string, data:Uint8Array}>}
 */
export function buildProjectFiles({ name, kind, entry, wasm, segments, stats, now }) {
  const title = name.replace(/[^A-Za-z0-9._-]+/g, '-');
  const manifest = {
    name: title,
    generator: 'xenon-recompiler',
    kind,
    entry,
    entryHex: hex(entry),
    stats,
    segments: segments.map((s, i) => ({ addr: hex(s.addr), file: `segment-${i}.bin`, bytes: s.data.length })),
    memoryBytes: 64 * 1024 * 1024,
    guestMemMask: '0x03ffffff',
    exitDoor: '0x00f00ffc',
    consoleMMIO: '0x00f00000',
    generatedAt: (now ?? new Date()).toISOString(),
  };
  const entryHex = entry.toString(16);
  const files = [
    { name: 'README.md', data: te.encode(readme(title, kind, stats, entry)) },
    { name: 'manifest.json', data: te.encode(JSON.stringify(manifest, null, 2)) },
    { name: 'index.html', data: te.encode(indexHtml(title)) },
    { name: 'runtime.js', data: te.encode(RUNTIME_JS) },
    { name: 'guest-wasm.js', data: te.encode(guestWasmJs(segments, wasm)) },
    { name: 'guest.wasm', data: wasm },
    { name: 'run.js', data: te.encode(RUN_JS) },
    { name: 'docs/KERNEL.md', data: te.encode(KERNEL_MD) },
    { name: 'kernel/.gitkeep', data: new Uint8Array(0) },
  ];
  segments.forEach((s, i) => {
    files.push({ name: `segment-${i}.bin`, data: s.data });
  });
  // guest.bin: concatenated segments for convenience (documented in README as split-by-segment)
  const guestBin = new Uint8Array(segments.reduce((n, s) => n + s.data.length, 0));
  let p = 0;
  for (const s of segments) { guestBin.set(s.data, p); p += s.data.length; }
  files.push({ name: 'guest.bin', data: guestBin });
  return files;
}
