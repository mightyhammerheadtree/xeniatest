/**
 * templates.js — file contents for the downloadable recompiler project.
 *
 * The exported archive ships a pure-HLE runtime (xenia-style): hle.js +
 * hle_tables.js reimplement the kernel surface as host calls, so the guest
 * runs with no kernel dump, no BIOS and no firmware of any kind.
 *
 * The zip is designed to run with zero tooling:
 *   - index.html + guest-wasm.js + runtime.js : double-clickable browser runner
 *     (classic scripts, works from file://, no server, no modules, no fetch).
 *   - run.js                                : optional node runner (no deps).
 *   - guest.wasm / guest.bin                : the recompiled module + image.
 *   - hle.js / hle_tables.js / docs/HLE.md  : the pure-HLE kernel (xenia-style).
 *   - manifest.json                         : build metadata + HLE import map.
 *
 * Everything is generated locally from YOUR dump. The archive contains code
 * derived from that dump; keep it for personal use (see docs/HLE.md).
 */

