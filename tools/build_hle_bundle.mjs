#!/usr/bin/env node
/**
 * build_hle_bundle.mjs — regenerate public/js/recomp/hle_bundle.js.
 *
 * The exported project zip must ship the HLE host (hle.js), the export
 * tables (hle_tables.js) and the HLE doc as byte-identical copies of the
 * files under public/. The browser zip builder (templates.js) runs with no
 * file system and no fetch in node tests, so the sources are embedded as
 * strings in a small generated module. This script is the only thing that
 * writes hle_bundle.js; `npm run test` fails if it is out of date
 * (core/tests/test_hle_bundle.mjs).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const enc = (s) => JSON.stringify(s);

const hleJs = read('public/js/recomp/hle.js');
const hleTables = read('public/js/recomp/hle_tables.js');
const hleDoc = read('docs/HLE.md');

const out = `/**
 * hle_bundle.js — GENERATED by tools/build_hle_bundle.mjs. Do not edit.
 *
 * Byte-identical copies of the shipping HLE files, embedded so the exported
 * project zip builder can run without a filesystem (browser) or network.
 * Regenerate with: npm run build:hle-bundle
 */
export const HLE_JS_SOURCE = ${enc(hleJs)};
export const HLE_TABLES_SOURCE = ${enc(hleTables)};
export const HLE_DOC_SOURCE = ${enc(hleDoc)};
`;

writeFileSync(join(root, 'public/js/recomp/hle_bundle.js'), out);
console.log('hle_bundle.js written:', (out.length / 1024).toFixed(1), 'KB');
