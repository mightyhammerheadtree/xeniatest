#!/usr/bin/env python3
"""
generate_hle_tables.py — regenerate public/js/recomp/hle_tables.js from the
xenia-canary export tables.

The generated file contains ONLY ordinal -> {name, kind} maps for the three
kernel modules (xboxkrnl, xam, xbdm). It embeds no code — just the public
export names/ordinals published in xenia-canary under the BSD 3-Clause
license (see THIRD_PARTY_NOTICES.md).

Usage:
    # 1. Fetch the tables (BSD-3-Clause, xenia-canary):
    curl -H "Accept: application/vnd.github.raw" -o xboxkrnl_table.inc \
        https://api.github.com/repos/xenia-canary/xenia-canary/contents/src/xenia/kernel/xboxkrnl/xboxkrnl_table.inc?ref=canary_experimental
    # ... same for xam/xam_table.inc and xbdm/xbdm_table.inc
    # 2. Generate:
    python3 tools/generate_hle_tables.py xboxkrnl_table.inc xam_table.inc xbdm_table.inc
"""
import re
import sys
from pathlib import Path

ENTRY = re.compile(r'XE_EXPORT\(\s*([A-Za-z0-9_]+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*([A-Za-z0-9_]+)\s*,\s*(kFunction|kVariable)\s*\)')
MODULE_IDS = {'xboxkrnl', 'xam', 'xbdm'}

def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    out_path = Path(__file__).resolve().parent.parent / 'public' / 'js' / 'recomp' / 'hle_tables.js'
    modules = {}
    for path in sys.argv[1:]:
        text = Path(path).read_text(encoding='utf-8')
        count = 0
        for m in ENTRY.finditer(text):
            module, ordinal_s, name, kind = m.groups()
            if module not in MODULE_IDS:
                continue
            ordinal = int(ordinal_s, 0)
            modules.setdefault(module, []).append((ordinal, name, 'function' if kind == 'kFunction' else 'variable'))
            count += 1
        print(f'{path}: {count} exports')
    total = 0
    lines = [
        '/**',
        ' * hle_tables.js — GENERATED by tools/generate_hle_tables.py from',
        ' * xenia-canary (BSD 3-Clause, Copyright 2021 Ben Vanik and contributors):',
        ' *   src/xenia/kernel/xboxkrnl/xboxkrnl_table.inc',
        ' *   src/xenia/kernel/xam/xam_table.inc',
        ' *   src/xenia/kernel/xbdm/xbdm_table.inc',
        ' * Do not edit by hand; re-run the generator instead.',
        ' *',
        ' * UMD: sets globalThis.XenonHLETables in browsers/modules/classic',
        ' * scripts, and module.exports under CommonJS.',
        ' */',
        '(function (global) {',
        "  'use strict';",
        '  const XENIA_EXPORTS = {',
    ]
    for module in ('xboxkrnl', 'xam', 'xbdm'):
        entries = sorted(modules.get(module, []), key=lambda e: e[0])
        total += len(entries)
        lines.append(f'    {module}: new Map([')
        for ordinal, name, _kind in entries:
            lines.append(f"      [0x{ordinal:08x}, '{name}'],")
        lines.append('    ]),')
    lines.append('  };')
    lines.append('  const api = { XENIA_EXPORTS };')
    lines.append("  if (typeof module !== 'undefined' && module.exports) module.exports = api;")
    lines.append('  global.XenonHLETables = api;')
    lines.append("})(typeof self !== 'undefined' ? self : globalThis);")
    lines.append('')
    out_path.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {out_path} ({total} exports)')
    return 0

if __name__ == '__main__':
    sys.exit(main())
